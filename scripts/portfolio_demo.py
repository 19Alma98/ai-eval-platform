#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SDK_DIR = ROOT / "sdk"
APP_DIR = ROOT / "examples" / "hr_it_assistant"
POLICY_PATH = APP_DIR / "opengrade.yaml"
BACKEND_DIR = ROOT / "backend"

sys.path.insert(0, str(SDK_DIR / "src"))

from opengrade import Client  # noqa: E402
from opengrade.models import ProjectResponse  # noqa: E402


def ensure_project(client: Client, slug: str, name: str) -> ProjectResponse:
    for project in client.projects.list():
        if project.slug == slug:
            print(f"reusing project {slug} ({project.id})")
            return project
    project = client.projects.create(name=name, slug=slug)
    print(f"created project {slug} ({project.id})")
    return project


def ensure_metrics_pack(client: Client, project_id: str) -> None:
    pack = client.metrics_packs.ensure(project_id)
    kinds = [e.kind for e in pack.entries]
    print(f"metrics pack ready: {', '.join(kinds)}")


def run_experiment(
    model: str,
    *,
    name: str,
    base: str,
    project_slug: str,
    baseline: str | None = None,
) -> dict[str, Any]:
    """Run hr_it_assistant ``--eval``: one opengrade.evaluate experiment over the gold rows.

    The SDK creates (or reuses) the gold dataset, binds every trace to its item,
    uploads outputs and scores with the project metrics pack.
    """
    cmd = [
        "uv",
        "run",
        "--extra",
        "openai",
        "--with",
        "openai",
        "python",
        str(APP_DIR / "main.py"),
        "--eval",
        "--json",
        "--model",
        model,
        "--name",
        name,
    ]
    if baseline:
        cmd += ["--baseline", baseline]
    env = os.environ.copy()
    env["OPENGRADE_TRACKING_URI"] = base
    env["OPENGRADE_PROJECT_SLUG"] = project_slug
    env["OLLAMA_HOST"] = os.getenv("OLLAMA_HOST", "http://localhost:11434")
    print(f"running hr_it_assistant --eval model={model} name={name}")
    proc = subprocess.run(
        cmd,
        cwd=str(SDK_DIR),
        env=env,
        check=True,
        capture_output=True,
        text=True,
    )
    if proc.stderr.strip():
        print(proc.stderr.strip(), file=sys.stderr)
    lines = [ln for ln in proc.stdout.splitlines() if ln.strip()]
    if not lines:
        raise RuntimeError(f"hr_it_assistant --eval printed no result (model={model})")
    result: dict[str, Any] = json.loads(lines[-1])
    print(f"  {name}: status={result['status']} errors={result['errors']}")
    for metric, mean in (result.get("metrics") or {}).items():
        print(f"    {metric}: mean={mean}")
    print(f"  {result['url']}")
    return result


def write_policy(
    *,
    base: str,
    project_id: str,
    experiment_id: str,
    baseline_experiment_id: str,
) -> Path:
    text = f"""# Generated by scripts/portfolio_demo.py — meta fields stripped by CLI.
api_base_url: {base}
project_id: {project_id}
experiment_id: {experiment_id}
baseline_experiment_id: {baseline_experiment_id}

hit_at_k:
  min: 0.8
groundedness:
  min: 0.7
correctness:
  min: 0.7
latency:
  p95_max_ms: 30000
regression:
  max_delta: -0.05
"""
    POLICY_PATH.write_text(text, encoding="utf-8")
    print(f"wrote {POLICY_PATH}")
    return POLICY_PATH


def run_opengrade_check(policy: Path, base: str) -> int:
    cmd = [
        "uv",
        "run",
        "opengrade",
        "check",
        "--policy",
        str(policy),
        "--base-url",
        base,
    ]
    print("running:", " ".join(cmd))
    proc = subprocess.run(cmd, cwd=str(BACKEND_DIR), check=False)
    return proc.returncode


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-url", default=os.getenv("OPENGRADE_TRACKING_URI", "http://localhost:8000"))
    parser.add_argument("--project-slug", default="hr-it-assistant")
    parser.add_argument("--skip-check", action="store_true", help="Skip opengrade check subprocess")
    args = parser.parse_args(argv)

    base = args.base_url.rstrip("/")
    client = Client(base, timeout=120.0)
    health = client.health()
    if health.status != "ok":
        raise SystemExit(f"API unhealthy at {base}/health: {health}")

    project = ensure_project(client, args.project_slug, "Acme People Ops")
    project_id = project.id
    ensure_metrics_pack(client, project_id)

    stamp = time.strftime("%Y%m%d-%H%M%S")
    model1 = os.getenv("OLLAMA_MODEL1", os.getenv("OLLAMA_MODEL", "gemma4:e2b"))
    model2 = os.getenv("OLLAMA_MODEL2", "tinyllama")
    print(f"MODEL1 (baseline)={model1}")
    print(f"MODEL2 (candidate)={model2}")

    baseline = run_experiment(
        model1, name=f"baseline-{stamp}", base=base, project_slug=args.project_slug
    )
    candidate = run_experiment(
        model2,
        name=f"candidate-{stamp}",
        base=base,
        project_slug=args.project_slug,
        baseline=baseline["experiment_id"],
    )
    baseline_id = baseline["experiment_id"]
    candidate_id = candidate["experiment_id"]

    compare = client.experiments.compare(candidate_id, baseline_id)
    print("compare:")
    print(compare.model_dump_json(indent=2))

    policy = write_policy(
        base=base,
        project_id=project_id,
        experiment_id=candidate_id,
        baseline_experiment_id=baseline_id,
    )

    print(f"\nOpen UI: http://localhost:3000  (project slug={args.project_slug})")
    print("Flow: Test set → Metrics → Runs")
    print(f"API project id: {project_id}")

    if args.skip_check:
        print("skipping opengrade check")
        return 0

    code = run_opengrade_check(policy, base)
    if code == 0:
        print("gate passed")
        return 0
    if code == 1:
        print("gate failed (regression or quality threshold)")
        return 0
    print(f"opengrade check failed with unexpected exit {code}", file=sys.stderr)
    return code


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except subprocess.CalledProcessError as exc:
        print(exc.stderr or exc, file=sys.stderr)
        raise SystemExit(exc.returncode) from exc
